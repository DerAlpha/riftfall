const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function fmtBytes(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / (1024 * 1024)).toFixed(1)} MB`;
}

async function loadDefs() {
  try {
    return await import(pathToFileURL(DEFS_FILE).href);
  } catch (nativeErr) {
    try {
      const ts = (await import('typescript')).default;
      const source = await readFile(DEFS_FILE, 'utf8');
      const js = ts.transpileModule(source, {
        compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
      }).outputText;
      return await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
    } catch (tsErr) {
      throw new Error(
        `cannot load ${DEFS_FILE}: ${nativeErr.message}; TypeScript fallback: ${tsErr.message}`,
        {
          cause: tsErr,
        },
      );
    }
  }
}

class HttpError extends Error {
  constructor(status, url) {
    super(`HTTP ${status} for ${url}`);
    this.status = status;
  }
}

async function fetchRetry(url, { as, timeoutMs, cfg }) {
  let lastErr;
  for (let attempt = 0; attempt <= cfg.retries; attempt++) {
    try {
      const res = await fetch(url, {
        signal: AbortSignal.timeout(timeoutMs),
        headers: { 'User-Agent': cfg.userAgent },
      });
      if (!res.ok) throw new HttpError(res.status, url);
      return as === 'json' ? await res.json() : Buffer.from(await res.arrayBuffer());
    } catch (err) {
      lastErr = err;
      const permanent =
        err instanceof HttpError && err.status >= 400 && err.status < 500 && err.status !== 429;
      if (permanent || attempt === cfg.retries) break;
      const delay = cfg.retryBaseDelayMs * 2 ** attempt;
      console.warn(`  ! ${err.message ?? err} – retry ${attempt + 1}/${cfg.retries} in ${delay} ms`);
      await sleep(delay);
    }
  }
  throw lastErr;
}

function md5(buf) {
  return createHash('md5').update(buf).digest('hex');
}

async function fileMatches(absPath, meta) {
  try {
    const st = await stat(absPath);
    if (!st.isFile() || st.size === 0) return false;
    if (meta?.size !== undefined && st.size !== meta.size) return false;
    if (meta?.md5) return md5(await readFile(absPath)) === meta.md5;
    return true;
  } catch {
    return false;
  }
}

async function exists(absPath) {
  try {
    return (await stat(absPath)).isFile();
  } catch {
    return false;
  }
}

/** Write via a temp file + rename: readers never see a truncated file, even after a crash. */
async function writeFileAtomic(absPath, data) {
  const tmp = `${absPath}.tmp`;
  await writeFile(tmp, data);
  await rename(tmp, absPath);
}

/** Assets of the previous available.json (null if missing, unreadable or another version). */
async function readPreviousIndex(indexPath, version) {
  try {
    const old = JSON.parse(await readFile(indexPath, 'utf8'));
    return old?.version === version && old.assets && typeof old.assets === 'object' ? old.assets : null;
  } catch {
    return null;
  }
}

/** Base-relative, forward-slash path of a file below public/ (the form the index uses). */
function publicRel(absPath) {
  return relative(PUBLIC_DIR, absPath).split(sep).join('/');
}

/**
 * Deletes files below absDir that are not in `keep` (base-relative paths) and directories that end
 * up empty. Returns how many entries remain in absDir.
 */
async function pruneDir(absDir, keep, stats) {
  let entries;
  try {
    entries = await readdir(absDir, { withFileTypes: true });
  } catch {
    return 0;
  }
  let remaining = 0;
  for (const entry of entries) {
    const abs = join(absDir, entry.name);
    if (entry.isDirectory()) {
      if ((await pruneDir(abs, keep, stats)) === 0) await rmdir(abs);
      else remaining++;
      continue;
    }
    const rel = publicRel(abs);
    if (keep.has(rel)) {
      remaining++;
      continue;
    }
    stats.bytes += (await stat(abs)).size;
    await rm(abs, { force: true });
    stats.removed++;
    console.info(`  pruned public/${rel}`);
  }
  return remaining;
}

/** Poly Haven files JSON: map key → resolution → format → { url, md5, size }. */
function pickFile(filesJson, key, resolutions, format) {
  const byRes = filesJson?.[key];
  if (!byRes) return null;
  for (const res of resolutions) {
    const file = byRes[res]?.[format];
    if (file?.url) return { res, url: file.url, md5: file.md5, size: file.size };
  }
  return null;
}

async function runLimited(items, limit, fn) {
  let next = 0;
  const worker = async () => {
    while (next < items.length) {
      const i = next++;
      await fn(items[i], i);
    }
  };
  await Promise.all(Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, worker));
}

