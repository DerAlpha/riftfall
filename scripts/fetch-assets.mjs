async function main() {
  await reexecWithEnvProxy();
  const defs = await loadDefs();
  const {
    ASSET_DEFS,
    ASSETS,
    POLYHAVEN,
    polyHavenHdriPath,
    polyHavenTexturePath,
    withExtension,
    SRGB_TEXTURE_ROLES,
  } = defs;
  const cfg = ASSETS.fetch;
  const selected = ASSET_DEFS.filter((d) => flags.only.length === 0 || flags.only.includes(d.id));
  const ktx2Enabled = !flags.noKtx2 && !flags.dryRun && hasTool(ASSETS.ktx2.tool);
  const indexPath = join(PUBLIC_DIR, ASSETS.indexFile);
  const previousAssets = await readPreviousIndex(indexPath, ASSETS.indexVersion);

  console.info(`RIFTFALL asset fetch – ${selected.length} asset(s) from Poly Haven (CC0) → public/assets/`);
  console.info(
    ktx2Enabled
      ? `  KTX2: "${ASSETS.ktx2.tool}" found – converting textures (ETC1S color, UASTC data/normals)`
      : `  KTX2: ${flags.noKtx2 ? 'disabled (--no-ktx2)' : `"${ASSETS.ktx2.tool}" not on PATH – JPG only`}`,
  );

  const results = [];
  const unsupported = new Set();

  await runLimited(selected, cfg.concurrency, async (def) => {
    const result = {
      id: def.id,
      type: def.type,
      files: {},
      ktx2: {},
      /** role → conversionSignature of the KTX2 file. */
      ktx2Args: {},
      downloaded: 0,
      cached: 0,
      bytes: 0,
      errors: [],
      warnings: [],
    };
    results.push(result);
    const { assetId } = def.source;
    const resolutions = [
      def.source.resolution,
      ...cfg.resolutionFallback.filter((r) => r !== def.source.resolution),
    ];

    if (def.source.provider !== 'polyhaven' || (def.type !== 'hdri' && def.type !== 'textureSet')) {
      unsupported.add(def.id);
      result.errors.push(`unsupported source/type (${def.source.provider}/${def.type})`);
      return;
    }

    let filesJson = null;
    try {
      filesJson = await fetchRetry(`${POLYHAVEN.apiBase}/files/${assetId}`, {
        as: 'json',
        timeoutMs: cfg.requestTimeoutMs,
        cfg,
      });
    } catch (err) {
      result.errors.push(`Poly Haven API unreachable (${err.message ?? err}) – indexing local files only`);
    }

    // Credit check (non-fatal): warn if Poly Haven lists different authors than defs/assets.ts.
    if (filesJson && !flags.dryRun) {
      try {
        const info = await fetchRetry(`${POLYHAVEN.apiBase}/info/${assetId}`, {
          as: 'json',
          timeoutMs: cfg.requestTimeoutMs,
          cfg,
        });
        const authors = Object.keys(info.authors ?? {})
          .sort()
          .join(', ');
        const credited = def.credit.author
          .split(',')
          .map((a) => a.trim())
          .sort()
          .join(', ');
        if (authors && authors !== credited)
          result.warnings.push(`credit authors differ from Poly Haven: "${authors}"`);
      } catch {
        // informational only
      }
    }

    /** role → { key, format, pathFor(res) } */
    const wanted = [];
    if (def.type === 'hdri') {
      wanted.push({
        role: 'hdr',
        key: POLYHAVEN.hdriKey,
        format: POLYHAVEN.hdriFormat,
        pathFor: (r) => polyHavenHdriPath(assetId, r),
        required: true,
      });
    } else {
      for (const role of POLYHAVEN.primaryTextureRoles) {
        const m = POLYHAVEN.textureMaps[role];
        wanted.push({
          role,
          key: m.key,
          format: POLYHAVEN.textureFormat,
          pathFor: (r) => polyHavenTexturePath(assetId, role, r),
          required: role === 'map',
        });
      }
      const hasArm =
        !filesJson ||
        pickFile(filesJson, POLYHAVEN.textureMaps.ormMap.key, resolutions, POLYHAVEN.textureFormat);
      if (!hasArm) {
        for (const role of POLYHAVEN.fallbackTextureRoles) {
          const m = POLYHAVEN.textureMaps[role];
          wanted.push({
            role,
            key: m.key,
            format: POLYHAVEN.textureFormat,
            pathFor: (r) => polyHavenTexturePath(assetId, role, r),
            required: false,
          });
        }
      }
    }

    for (const w of wanted) {
      if (!filesJson) {
        // Offline: keep whatever a previous run downloaded.
        for (const r of resolutions) {
          const rel = w.pathFor(r);
          if (await exists(join(PUBLIC_DIR, rel))) {
            result.files[w.role] = rel;
            result.cached++;
            break;
          }
        }
        continue;
      }
      const pick = pickFile(filesJson, w.key, resolutions, w.format);
      if (!pick) {
        (w.required ? result.errors : result.warnings).push(
          `no ${w.key} (${w.format}) at ${resolutions.join('/')}`,
        );
        continue;
      }
      const rel = w.pathFor(pick.res);
      const abs = join(PUBLIC_DIR, rel);
      if (flags.dryRun) {
        console.info(`  [dry-run] ${def.id}.${w.role} ← ${pick.url} (${fmtBytes(pick.size ?? 0)})`);
        result.files[w.role] = rel;
        continue;
      }
      if (!flags.force && (await fileMatches(abs, pick))) {
        result.files[w.role] = rel;
        result.cached++;
        continue;
      }
      try {
        const buf = await fetchRetry(pick.url, { as: 'buffer', timeoutMs: cfg.downloadTimeoutMs, cfg });
        if (pick.md5 && md5(buf) !== pick.md5) throw new Error(`checksum mismatch for ${pick.url}`);
        await mkdir(dirname(abs), { recursive: true });
        await writeFile(`${abs}.part`, buf);
        await rename(`${abs}.part`, abs);
        result.files[w.role] = rel;
        result.downloaded++;
        result.bytes += buf.length;
      } catch (err) {
        await rm(`${abs}.part`, { force: true });
        (w.required ? result.errors : result.warnings).push(`${w.role}: ${err.message ?? err}`);
      }
    }

    if (def.type === 'textureSet' && !result.files.map)
      result.errors.push('albedo map missing – set unusable');

    if (ktx2Enabled && def.type === 'textureSet') {
      for (const [role, rel] of Object.entries(result.files)) {
        const src = join(PUBLIC_DIR, rel);
        const outRel = withExtension(rel, 'ktx2');
        const out = join(PUBLIC_DIR, outRel);
        // toktx writes its output in place: convert into a temp file (still *.ktx2) and rename.
        const tmp = join(PUBLIC_DIR, withExtension(rel, 'part.ktx2'));
        const toolArgs = SRGB_TEXTURE_ROLES.includes(role) ? ASSETS.ktx2.colorArgs : ASSETS.ktx2.dataArgs;
        const signature = conversionSignature(ASSETS.ktx2.tool, toolArgs);
        try {
          const fresh =
            !flags.force &&
            previousAssets?.[def.id]?.ktx2Args?.[role] === signature &&
            (await ktx2Complete(out)) &&
            (await stat(out)).mtimeMs >= (await stat(src)).mtimeMs;
          if (!fresh) {
            const r = await runTool(ASSETS.ktx2.tool, [...toolArgs, tmp, src], ASSETS.ktx2.timeoutMs);
            if (!r.ok) throw new Error(r.message || 'conversion failed');
            if (!(await ktx2Complete(tmp))) throw new Error('conversion wrote an incomplete KTX2 file');
            await rename(tmp, out);
          }
          result.ktx2[role] = outRel;
          result.ktx2Args[role] = signature;
        } catch (err) {
          await rm(tmp, { force: true });
          await rm(out, { force: true });
          result.warnings.push(`KTX2 ${role}: ${err.message ?? err}`);
        }
      }
    }
  });

  results.sort((a, b) => selected.findIndex((d) => d.id === a.id) - selected.findIndex((d) => d.id === b.id));

  // --- available.json -------------------------------------------------------
  const usable = results.filter((r) => (r.type === 'hdri' ? r.files.hdr : r.files.map));
  const partial = flags.only.length > 0;
  let pruned = null;
  if (!flags.dryRun) {
    const assets = {};
    if (partial) {
      // Partial run: keep entries of defined assets that were not processed.
      if (!previousAssets)
        console.warn(
          '  ! previous index missing or unreadable – it will list only the processed assets (run without --only to rebuild it)',
        );
      const defined = new Set(ASSET_DEFS.map((d) => d.id));
      const processed = new Set(results.map((r) => r.id));
      for (const [id, entry] of Object.entries(previousAssets ?? {})) {
        if (!defined.has(id)) console.info(`  index: dropped "${id}" (not in src/defs/assets.ts any more)`);
        else if (!processed.has(id)) assets[id] = entry;
      }
    }
    for (const r of usable) {
      assets[r.id] = {
        type: r.type,
        files: r.files,
        ...(Object.keys(r.ktx2).length > 0 ? { ktx2: r.ktx2, ktx2Args: r.ktx2Args } : {}),
      };
    }
    const index = { version: ASSETS.indexVersion, generatedAt: new Date().toISOString(), assets };
    await mkdir(dirname(indexPath), { recursive: true });
    await writeFileAtomic(indexPath, `${JSON.stringify(index, null, 2)}\n`);
    await writeCredits(ASSET_DEFS);

    // Without the previous index a partial run cannot know which files the other assets use.
    if (!flags.noPrune && !(partial && !previousAssets)) {
      const keep = new Set();
      const addPaths = (map) => Object.values(map ?? {}).forEach((rel) => keep.add(rel));
      for (const entry of Object.values(assets)) {
        addPaths(entry.files);
        addPaths(entry.ktx2);
      }
      // Files of processed assets that are not usable yet (e.g. only the albedo failed) stay for the next run.
      for (const r of results) {
        addPaths(r.files);
        addPaths(r.ktx2);
      }
      pruned = { removed: 0, bytes: 0 };
      for (const dir of [ASSETS.dirs.textures, ASSETS.dirs.hdri])
        await pruneDir(join(PUBLIC_DIR, dir), keep, pruned);
    }
  }

  // --- summary --------------------------------------------------------------
  console.info('');
  let failures = 0;
  for (const r of results) {
    const ok = usable.includes(r);
    if (!ok) failures++;
    const ktx = Object.keys(r.ktx2).length > 0 ? `, ${Object.keys(r.ktx2).length}× ktx2` : '';
    const what = `${Object.keys(r.files).length} file(s): ${r.downloaded} downloaded (${fmtBytes(r.bytes)}), ${r.cached} cached${ktx}`;
    console.info(`  ${ok ? '✔' : '✘'} ${r.id.padEnd(18)} ${what}`);
    for (const w of r.warnings) console.warn(`      warning: ${w}`);
    for (const e of r.errors) console.warn(`      ${ok ? 'note' : 'error'}: ${e}`);
  }
  console.info('');
  if (!flags.dryRun)
    console.info(
      `  index: public/${ASSETS.indexFile} (${usable.length}/${results.length} available), CREDITS.md updated`,
    );
  if (pruned && pruned.removed > 0)
    console.info(`  pruned ${pruned.removed} unreferenced file(s) (${fmtBytes(pruned.bytes)})`);
  if (failures > 0) {
    console.warn(`  ${failures} asset(s) unavailable – the game uses procedural fallbacks for them.`);
    if (flags.strict) process.exit(1);
  }
}

/** Markdown table with padded columns (the layout Prettier produces, so reruns cause no churn). */
function markdownTable(header, rows) {
  const widths = header.map((h, c) => Math.max(3, h.length, ...rows.map((r) => r[c].length)));
  const line = (cells) => `| ${cells.map((cell, c) => cell.padEnd(widths[c])).join(' | ')} |`;
  return [line(header), line(widths.map((w) => '-'.repeat(w))), ...rows.map(line)];
}

async function writeCredits(assetDefs) {
  const lines = [
    CREDITS_BEGIN,
    '',
    ...markdownTable(
      ['Asset id', 'Asset', 'Author(s)', 'Source', 'License'],
      assetDefs.map((d) => [
        `\`${d.id}\``,
        d.credit.title,
        d.credit.author,
        d.credit.source,
        d.credit.license,
      ]),
    ),
    '',
    CREDITS_END,
  ];
  const section = lines.join('\n');
  let text;
  try {
    text = await readFile(CREDITS_FILE, 'utf8');
  } catch {
    text = `# Credits\n\n## Assets\n\n${CREDITS_BEGIN}\n${CREDITS_END}\n`;
  }
  const start = text.indexOf(CREDITS_BEGIN);
  const end = text.indexOf(CREDITS_END);
  const next =
    start >= 0 && end > start
      ? text.slice(0, start) + section + text.slice(end + CREDITS_END.length)
      : `${text.trimEnd()}\n\n## Assets\n\n${section}\n`;
  if (next !== text) await writeFileAtomic(CREDITS_FILE, next);
}

main().catch((err) => {
  console.warn(`fetch-assets: ${err?.stack ?? err}`);
  console.warn('Assets are optional – the game falls back to procedural textures/environment.');
  process.exit(flags.strict ? 1 : 0);
});
